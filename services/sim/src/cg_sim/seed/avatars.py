"""Generated abstract avatars: a flat silhouette on a colored background, as a PNG written with the
standard library only (deterministic bytes). Not a likeness of anyone."""

from __future__ import annotations

import random
import struct
import zlib

SIZE = 96
PALETTE = [
    ((231, 111, 81), (255, 236, 214)),
    ((42, 157, 143), (220, 245, 240)),
    ((38, 70, 83), (210, 228, 235)),
    ((233, 196, 106), (90, 64, 20)),
    ((244, 162, 97), (80, 40, 20)),
    ((106, 76, 147), (235, 225, 248)),
    ((25, 130, 196), (225, 240, 252)),
    ((138, 201, 38), (40, 70, 10)),
    ((255, 89, 94), (255, 230, 230)),
    ((76, 201, 240), (20, 60, 80)),
    ((181, 101, 118), (250, 230, 235)),
    ((96, 108, 56), (235, 240, 215)),
]

PROVENANCE = """# Avatar provenance

Every `u_*.png` in this folder is generated by `cg-sim seed` (`services/sim/src/cg_sim/avatars.py`):
an abstract silhouette on a flat color, drawn pixel by pixel from the persona's ID and the pool seed.
They depict no one and contain no third-party material.
{maya}"""

MAYA_PROVENANCE = """
`u_maya.jpg` is a copy of the Facebook clone's `facebook-clone/assets/images/maya.jpg`, an Unsplash
photo of a stock model used under the Unsplash license. Source, license and SHA-256 are recorded in
`facebook-clone/assets/provenance.md`. The person depicted is not Maya; Maya is fictional.
"""


def render_png(rng: random.Random) -> bytes:
    bg, fg = rng.choice(PALETTE)
    head_r = rng.uniform(15, 19)
    head_y = rng.uniform(36, 41)
    shoulder_w = rng.uniform(28, 34)
    rows = []
    for y in range(SIZE):
        row = bytearray([0])  # filter type 0
        for x in range(SIZE):
            dx, dy = x - SIZE / 2 + 0.5, y + 0.5
            in_head = dx * dx + (dy - head_y) ** 2 <= head_r * head_r
            in_body = dy >= 68 and (dx / shoulder_w) ** 2 + ((dy - 98) / 30) ** 2 <= 1
            row += bytes(fg if in_head or in_body else bg)
        rows.append(bytes(row))
    raw = b"".join(rows)

    def chunk(tag: bytes, data: bytes) -> bytes:
        return (
            struct.pack(">I", len(data)) + tag + data + struct.pack(">I", zlib.crc32(tag + data) & 0xFFFFFFFF)
        )

    header = struct.pack(">IIBBBBB", SIZE, SIZE, 8, 2, 0, 0, 0)
    return (
        b"\x89PNG\r\n\x1a\n"
        + chunk(b"IHDR", header)
        + chunk(b"IDAT", zlib.compress(raw, 9))
        + chunk(b"IEND", b"")
    )
